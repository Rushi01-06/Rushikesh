# Create a dictionary and display:All keys All values All key-value pairs
student_info = {
    "name": "Alex",
    "age": 21,
    "major": "Computer Science",
    "gpa": 3.8
}
print("--- All Keys ---")
print(student_info.keys())
print("\n--- All Values ---")
print(student_info.values())
print("\n--- All Key-Value Pairs ---")
print(student_info.items())
